/**
 * Copies docs/CHANGELOG.md into the UI as data, so the app can show what changed after it updates
 * itself without asking anyone for it. The notes ship inside the build: no request, nothing to
 * serve, and the same text offline as online.
 *
 * Run it whenever docs/CHANGELOG.md changes. A test pins the newest entry to the UI package's
 * version, so a release that forgets this fails before it ships.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "docs", "CHANGELOG.md");
const target = join(root, "packages", "ui", "src", "model", "changelog.generated.ts");

/**
 * Splits the changelog on its `## <version>` headings, keeping each entry's markdown as written.
 * Any other `## ` heading ends the entry above it and is left out, along with what follows it up to
 * the next version: that is where a note about the changelog itself goes, like where Helicon's
 * history starts.
 */
function parse(markdown) {
  const entries = [];
  const lines = markdown.split(/\r?\n/);
  let current = null;
  for (const line of lines) {
    const heading = /^## +(\d+\.\d+\.\d+) *$/.exec(line);
    if (heading || line.startsWith("## ")) {
      if (current) entries.push(current);
      current = heading ? { version: heading[1], lines: [] } : null;
      continue;
    }
    if (current) current.lines.push(line);
  }
  if (current) entries.push(current);
  return entries.map((entry) => ({ version: entry.version, body: entry.lines.join("\n").trim() }));
}

const entries = parse(readFileSync(source, "utf8"));
if (entries.length === 0) {
  throw new Error(`No "## <version>" headings found in ${source}`);
}

const file = `// Generated by scripts/sync-changelog.mjs from docs/CHANGELOG.md. Do not edit by hand.

/** One released version and the notes written for it, newest first. */
export interface ChangelogEntry {
  version: string;
  /** The entry's markdown, exactly as the changelog has it. */
  body: string;
}

export const CHANGELOG: readonly ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(target, file);
console.log(`wrote ${entries.length} entries to packages/ui/src/model/changelog.generated.ts (newest ${entries[0].version})`);
