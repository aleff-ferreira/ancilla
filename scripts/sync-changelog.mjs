/**
 * Ancilla Changelog Synchronization Utility
 *
 * Compiles docs/CHANGELOG.md into a static TypeScript module
 * (packages/ui/src/model/changelog.generated.ts) for offline presentation
 * in the Ancilla desktop and web interfaces.
 *
 * Usage:
 *   node scripts/sync-changelog.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const changelogSourcePath = join(repositoryRoot, "docs", "CHANGELOG.md");
const generatedTargetPath = join(
  repositoryRoot,
  "packages",
  "ui",
  "src",
  "model",
  "changelog.generated.ts",
);

/**
 * Parses markdown release notes into versioned entries.
 *
 * Splits on `## <version>` headings (e.g. `## 0.29.0`). Non-version `## ` headings
 * (such as `## Unreleased` or general documentation notes) terminate the active
 * version entry and are excluded from the generated release dataset.
 */
export function parseChangelogMarkdown(markdown) {
  const entries = [];
  const lines = markdown.split(/\r?\n/);
  let activeEntry = null;

  for (const line of lines) {
    const versionMatch = /^## +(\d+\.\d+\.\d+) *$/.exec(line);
    if (versionMatch || line.startsWith("## ")) {
      if (activeEntry) {
        entries.push(activeEntry);
      }
      activeEntry = versionMatch ? { version: versionMatch[1], lines: [] } : null;
      continue;
    }

    if (activeEntry) {
      activeEntry.lines.push(line);
    }
  }

  if (activeEntry) {
    entries.push(activeEntry);
  }

  return entries.map((entry) => ({
    version: entry.version,
    body: entry.lines.join("\n").trim(),
  }));
}

export function generateTypeScriptChangelog(entries) {
  return `// Generated by scripts/sync-changelog.mjs from docs/CHANGELOG.md. Do not edit by hand.

/** One released version and the notes written for it, newest first. */
export interface ChangelogEntry {
  version: string;
  /** The entry's markdown, exactly as the changelog has it. */
  body: string;
}

export const CHANGELOG: readonly ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

export function syncChangelog(sourcePath = changelogSourcePath, targetPath = generatedTargetPath) {
  const content = readFileSync(sourcePath, "utf8");
  const entries = parseChangelogMarkdown(content);

  if (entries.length === 0) {
    throw new Error(`No "## <version>" headings found in ${sourcePath}`);
  }

  const generatedCode = generateTypeScriptChangelog(entries);
  writeFileSync(targetPath, generatedCode);
  console.log(
    `wrote ${entries.length} entries to packages/ui/src/model/changelog.generated.ts (newest ${entries[0].version})`,
  );
  return entries;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/"))) {
  syncChangelog();
}
